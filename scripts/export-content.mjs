// Export the site's TypeScript content into seed/content.json and seed/seed.sql.
// The heavy lifting (bundling, JSON parsing) happens locally, never in the Worker.
import { build } from "esbuild";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

const root = process.cwd();
const tmp = path.join(root, "scripts", ".content-entry.mjs");

await build({
  entryPoints: [path.join(root, "scripts", "content-entry.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outfile: tmp,
  logLevel: "silent",
});

const mod = await import(`${pathToFileURL(tmp).href}?v=${Date.now()}`);
const { documents, settings } = mod.getContent();

const esc = (value) => String(value).replace(/'/g, "''");
const now = new Date().toISOString();

const statements = [
  "-- Generated by scripts/export-content.mjs — seeds Cloudflare D1 with the site's current content.",
  "PRAGMA foreign_keys = ON;",
  ...documents.map(
    (doc) =>
      `INSERT INTO documents (id, type, slug, status, sort, data, created_at, updated_at, updated_by)\n` +
      `VALUES ('${esc(`${doc.type}:${doc.slug}`)}', '${esc(doc.type)}', '${esc(doc.slug)}', 'published', ${Number(doc.sort) || 0}, '${esc(JSON.stringify(doc.data))}', '${now}', '${now}', 'seed')\n` +
      `ON CONFLICT(id) DO UPDATE SET status = excluded.status, sort = excluded.sort, data = excluded.data, updated_at = excluded.updated_at, updated_by = excluded.updated_by;`,
  ),
  ...Object.entries(settings).map(
    ([key, value]) =>
      `INSERT INTO settings (key, value, updated_at, updated_by) VALUES ('${esc(key)}', '${esc(JSON.stringify(value))}', '${now}', 'seed')\n` +
      `ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at, updated_by = excluded.updated_by;`,
  ),
  `INSERT INTO meta (key, value, updated_at) VALUES ('content_version', '1', '${now}') ON CONFLICT(key) DO UPDATE SET value = CAST(CAST(meta.value AS INTEGER) + 1 AS TEXT), updated_at = excluded.updated_at;`,
  `INSERT INTO meta (key, value, updated_at) VALUES ('staging_version', '1', '${now}') ON CONFLICT(key) DO UPDATE SET value = CAST(CAST(meta.value AS INTEGER) + 1 AS TEXT), updated_at = excluded.updated_at;`,
];

await mkdir(path.join(root, "seed"), { recursive: true });
await writeFile(path.join(root, "seed", "content.json"), JSON.stringify({ documents, settings }, null, 2));
await writeFile(path.join(root, "seed", "seed.sql"), statements.join("\n\n") + "\n");
await mkdir(path.join(root, "public"), { recursive: true });
await writeFile(path.join(root, "public", "content-seed.json"), JSON.stringify({ documents, settings }));

const base = "https://bce-construction.com";
const escapeXml = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const staticPages = [
  ["", "1.0"],
  ["/?about", "0.8"],
  ["/?businesses", "0.9"],
  ["/?projects", "0.9"],
  ["/?quality", "0.7"],
  ["/?capabilities", "0.7"],
  ["/?quote", "0.8"],
  ["/?recruitment", "0.6"],
  ["/?resources", "0.6"],
  ["/?blog", "0.7"],
];
const sitemapUrls = [
  ...staticPages.map(([path, priority]) => ({ loc: `${base}${path}`, priority })),
  ...documents.filter((doc) => doc.type === "businesses").map((doc) => ({ loc: `${base}/?business=${encodeURIComponent(doc.slug)}`, priority: "0.7" })),
  ...documents.filter((doc) => doc.type === "projects").map((doc) => ({ loc: `${base}/?project=${encodeURIComponent(doc.slug)}`, priority: "0.6" })),
  ...documents.filter((doc) => doc.type === "posts").map((doc) => ({ loc: `${base}/?blog&post=${encodeURIComponent(doc.slug)}`, priority: "0.5" })),
];
const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...sitemapUrls.map(
    ({ loc, priority }) =>
      `  <url><loc>${escapeXml(loc)}</loc><changefreq>monthly</changefreq><priority>${priority}</priority></url>`,
  ),
  "</urlset>",
  "",
].join("\n");
await writeFile(path.join(root, "public", "sitemap.xml"), sitemap);

await rm(tmp, { force: true });

const byType = documents.reduce((acc, doc) => {
  acc[doc.type] = (acc[doc.type] ?? 0) + 1;
  return acc;
}, {});
console.log("Exported", documents.length, "documents:", byType);
console.log("Wrote seed/content.json and seed/seed.sql");
